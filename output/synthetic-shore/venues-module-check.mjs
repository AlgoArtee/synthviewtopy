import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

const generated = new URL('./.venues-check-module.mjs', import.meta.url);
const input = await fs.readFile(new URL('../../src/world/syntheticBeachVenues.ts', import.meta.url), 'utf8');
await fs.writeFile(generated, ts.transpileModule(input, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText);
globalThis.document = { createElement() { return { width: 0, height: 0, getContext() { return { fillRect() {}, strokeRect() {}, fillText() {} }; } }; } };
const { createSyntheticBeachVenues } = await import(pathToFileURL(generated.pathname.replace(/^\//, '')).href).catch(() => import(generated.href));
const venues = createSyntheticBeachVenues((_x, z) => z * 0.04);
assert.equal(venues.groundHeight(-48, 23), 23 * 0.04);
assert.equal(venues.groundHeight(-48, 32), 60 * 0.04 + 0.2);
assert.equal(venues.groundHeight(68, 31), 31 * 0.04);
assert.equal(venues.groundHeight(68, 40), 72 * 0.04 + 0.2);
assert.equal(venues.blocksMovement(68, 51), true);
venues.perform('toggle-house-door');
for (let frame = 0; frame < 100; frame++) venues.update(frame / 60);
assert.equal(venues.blocksMovement(68, 51), false);
assert.equal(venues.blocksMovement(55.8, 61), true);
assert.equal(venues.blocksMovement(-55.5, 50.7), true);
assert.equal(venues.blocksMovement(-48, 44), false);
assert.equal(venues.perform('serve-nebula').cocktail, 'Nebula Fizz');
assert.equal(venues.getSnapshot().cocktail, 'Nebula Fizz');
assert.equal(venues.group.getObjectByName('Your freshly mixed cocktail').visible, true);
venues.perform('clear-drink');
assert.equal(venues.group.getObjectByName('Your freshly mixed cocktail').visible, false);
venues.perform('toggle-house-lights');
assert.equal(venues.getSnapshot().house.lightsOn, false);
venues.update(4, true);
assert.equal(venues.getSnapshot().club.musicPlaying, true);
const hotspotIds = new Set(venues.hotspots.map((item) => item.id));
assert.deepEqual([...hotspotIds], ['club-dj', 'club-bar', 'beach-house']);
for (const hotspot of venues.hotspots) assert(hotspot.actions.some((action) => action.id === 'toggle-music'));
venues.dispose();
venues.dispose();
assert.equal(venues.group.children.length, 0);
await fs.unlink(generated);
console.log('Venue geometry, ramps, collision, door, cocktails, lights, music pulse and disposal passed.');
